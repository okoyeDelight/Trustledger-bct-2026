#!/usr/bin/env python3
"""Rebuild src/source_evidence.js from ORIGINAL organizer synthetic starter ZIP.

No artificial temperature records. Exact, selected source rows, verified by
(facility_id, timestamp); overlaps with independent power_outages.csv are
included as context, NOT asserted proof of causation or unit exposure.

Usage:
 python3 scripts/build_source_evidence.py --source "/path/to/Hackathon Starter Dataset.zip"
"""
from __future__ import annotations
import argparse
import csv
import io
import json
from pathlib import Path
from zipfile import ZipFile

CASE_TIMES = {
    "TL-024": ("HSP-024", [
        "2026-09-30 07:00:00", "2026-09-30 08:00:00", "2026-09-30 09:00:00",
        "2026-10-02 19:00:00", "2026-10-02 20:00:00", "2026-10-02 21:00:00"]),
    "TL-NBO-HOT": ("RBTC-NBO", [
        "2026-10-05 23:00:00", "2026-10-06 00:00:00", "2026-10-06 01:00:00",
        "2026-10-06 02:00:00", "2026-10-06 03:00:00"]),
    "TL-NBO-GLITCH": ("RBTC-NBO", [
        "2026-03-27 06:00:00", "2026-03-27 07:00:00", "2026-03-27 08:00:00",
        "2026-03-27 09:00:00", "2026-03-27 10:00:00", "2026-03-27 11:00:00"]),
    "TL-024-CONTROL": ("HSP-024", [
        "2026-10-02 19:00:00", "2026-10-02 20:00:00",
        "2026-10-02 21:00:00", "2026-10-02 22:00:00"]),
}

def parse(z, name):
    with z.open(name) as binary, io.TextIOWrapper(binary, encoding="utf-8-sig", newline="") as stream:
        yield from csv.DictReader(stream)

def extract(archive: Path):
    required = {(facility, timestamp)
                for facility, times in CASE_TIMES.values()
                for timestamp in times}
    with ZipFile(archive) as z:
        selected = {}
        for row in parse(z, "temperature_logs.csv"):
            key = (row["facility_id"], row["recorded_at"])
            if key in required:
                if key in selected:
                    raise ValueError(f"Duplicate source reading: {key}")
                selected[key] = {"at": row["recorded_at"].replace(" ", "T") + "+03:00",
                                 "c": float(row["temp_c"]),
                                 "facility_id": row["facility_id"],
                                 "source": "starter:temperature_logs.csv"}
        if set(selected) != required:
            raise ValueError(f"Source rows missing: {sorted(required - set(selected))}")
        all_outages = list(parse(z, "power_outages.csv"))

    cases = {}
    for case_id, (facility, times) in CASE_TIMES.items():
        outages = []
        for r in all_outages:
            if r["facility_id"] != facility:
                continue
            if r["end_time"] < times[0] or r["start_time"] > times[-1]:
                continue
            outages.append({
                "outage_id": r["outage_id"],
                "facility_id": facility,
                "start_time": r["start_time"],
                "end_time": r["end_time"],
                "duration_hours": float(r["duration_hours"]),
                "backup_power_engaged": r["backup_power_engaged"].lower() == "true",
                "source": "starter:power_outages.csv"
            })
        cases[case_id] = {
            "facility_id": facility,
            "source_readings": [selected[(facility, timestamp)] for timestamp in times],
            "overlapping_power_outages": outages,
            "exposure_provenance": "Facility-level sensor feed only; NO named fridge-to-unit history in starter dataset",
        }
    return cases

def render(cases):
    return ("// GENERATED by scripts/build_source_evidence.py from organizer's synthetic ZIP.\n"
            "// DO NOT edit numeric observations by hand; all times are EAT (+03:00).\n"
            "// Facility readings do not establish named-fridge or individual unit exposure.\n"
            "export const EVIDENCE_CASES = Object.freeze(" + json.dumps(cases, indent=2) + ");\n")

if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=Path("src/source_evidence.js"))
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(extract(args.source)), encoding="utf-8")
    print(f"Wrote {args.out}, with {len(CASE_TIMES)} verified synthetic case excerpts.")
